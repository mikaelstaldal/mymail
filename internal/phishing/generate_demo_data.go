//go:build ignore

// Run from the repo root:
// go run internal/phishing/generate_demo_data.go /path/to/public_suffix_list.dat
// The PSL input must be publicsuffix/list commit
// d6c92f1bbb7433e5db7b8405c25d4035fb8ff376, matching x/net v0.60.0.
// Confusables JSON is the unfiltered source→target mapping from Unicode 16.0.0
// confusables.txt (see UNICODE.md). Neither input is downloaded by the build.
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"

	"github.com/mikaelstaldal/mymail/internal/phishing"
	"golang.org/x/net/idna"
)

func main() {
	if len(os.Args) != 2 {
		panic("usage: generate_demo_data.go public_suffix_list.dat")
	}
	conf, err := os.ReadFile("internal/phishing/confusables.json")
	check(err)
	input, err := os.Open(os.Args[1])
	check(err)
	defer input.Close()
	rules := []string{}
	icann := false
	roots := map[string]bool{}
	scanner := bufio.NewScanner(input)
	for scanner.Scan() {
		s := strings.TrimSpace(scanner.Text())
		if s == "// ===BEGIN ICANN DOMAINS===" {
			icann = true
		}
		if s == "// ===END ICANN DOMAINS===" {
			icann = false
		}
		if s != "" && !strings.HasPrefix(s, "//") {
			rules = append(rules, s)
			if icann {
				parts := strings.Split(s, ".")
				root, err := idna.Lookup.ToASCII(parts[len(parts)-1])
				check(err)
				roots[root] = true
			}
		}
	}
	check(scanner.Err())
	tlds := []string{}
	for root := range roots {
		tlds = append(tlds, root)
	}
	sort.Strings(tlds)
	scripts := []string{}
	for name := range unicode.Scripts {
		if name != "Common" && name != "Inherited" {
			scripts = append(scripts, name)
		}
	}
	sort.Strings(scripts)
	folds := map[string]string{}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		s := string(r)
		if v := phishing.FoldRune(r); v != s {
			folds[s] = v
		}
	}
	// Validate that every PSL domain is accepted by the same IDNA implementation
	// used on the server. Browser URL performs its IDNA conversion at runtime.
	for _, rule := range rules {
		_, err := idna.Lookup.ToASCII(strings.TrimPrefix(strings.TrimPrefix(rule, "!"), "*."))
		check(err)
	}
	out, err := os.Create("web/ts/demo/phishing-data.ts")
	check(err)
	defer out.Close()
	_, err = fmt.Fprintln(out, "// Generated by internal/phishing/generate_demo_data.go; DO NOT EDIT.\n// Unicode 16 confusables (Unicode license), Go Unicode scripts/case folding,\n// and publicsuffix/list d6c92f1bbb7433e5db7b8405c25d4035fb8ff376 (MPL-2.0).\n// See internal/phishing/UNICODE.md and PUBLIC-SUFFIX-LICENSE.txt.")
	check(err)
	_, err = fmt.Fprintf(out, "const phishingConfusables: Record<string,string> = %s;\n", strings.TrimSpace(string(conf)))
	check(err)
	for _, v := range []struct {
		decl  string
		value any
	}{{"phishingSuffixRules", rules}, {"phishingICANNTLDs", tlds}, {"phishingScripts: string[]", scripts}, {"phishingCaseFold: Record<string,string>", folds}} {
		b, err := json.Marshal(v.value)
		check(err)
		_, err = fmt.Fprintf(out, "const %s = %s;\n", v.decl, b)
		check(err)
	}
	b, err := json.Marshal(folds)
	check(err)
	check(os.WriteFile("web/ts/util/casefold.ts", []byte(fmt.Sprintf("// Generated from Go phishing.FoldRune by internal/phishing/generate_demo_data.go; DO NOT EDIT.\nconst addressCaseFold: Record<string,string> = %s;\n\n/** Same address normalization as the contact repository and browser demo. */\nexport function foldContactAddress(address: string): string {\n  return Array.from(address, c => addressCaseFold[c] ?? c).join('');\n}\n", b)), 0644))
}
func check(err error) {
	if err != nil {
		panic(err)
	}
}
